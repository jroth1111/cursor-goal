#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const policyPath = path.join(root, "core/policy/destructive-shell.json");
const outPath = path.join(root, "core/.cursor/hooks/destructive-shell-policy.sh");

const policy = JSON.parse(readFileSync(policyPath, "utf8"));

const perlChecks = [];
for (const rule of policy.rules) {
  if (rule.id === "drop_database") {
    perlChecks.push("exit 0 if /\\bdrop\\s+database\\b/i;");
  } else if (rule.id === "force_git_push") {
    perlChecks.push(`if (/\\bgit\\b[\\s\\S]*\\bpush\\b/i &&
          /(?:^|[\\s;&|])(?:-f\\b|--force(?:[=\\s]|$)|--force-with-lease(?:[=\\s]|$)|\\+[^\\s;&|]+)/i) { exit 0; }`);
  } else if (rule.id === "recursive_rm") {
    perlChecks.push(`if (/(?:^|[\\s;&|])rm(?:[\\s;&|]|$)/i &&
          (/(?:^|[\\s;&|])-[a-z]*r[a-z]*f[a-z]*(?=$|[\\s;&|])/i ||
           /(?:^|[\\s;&|])-[a-z]*f[a-z]*r[a-z]*(?=$|[\\s;&|])/i ||
           /(?:^|[\\s;&|])(?:-[a-z]*r[a-z]*|--recursive)(?=$|[\\s;&|])[\\s\\S]*(?:^|[\\s;&|])(?:-[a-z]*f[a-z]*|--force)(?=$|[\\s;&|])/i ||
           /(?:^|[\\s;&|])(?:-[a-z]*f[a-z]*|--force)(?=$|[\\s;&|])[\\s\\S]*(?:^|[\\s;&|])(?:-[a-z]*r[a-z]*|--recursive)(?=$|[\\s;&|])/i)) { exit 0; }`);
  }
}

const grepPattern =
  "\\bdrop[[:space:]]+database\\b|\\bgit\\b.*\\bpush\\b.*(--force([=[:space:]]|$)|--force-with-lease([=[:space:]]|$)|(^|[[:space:]])-f([[:space:]]|$)|(^|[[:space:];&|])\\+[^[:space:];&|]+)|\\brm\\b.*(-[[:alpha:]]*r[[:alpha:]]*f|-[[:alpha:]]*f[[:alpha:]]*r|--recursive.*--force|--force.*--recursive)";

const body = `#!/usr/bin/env bash
# Generated by scripts/embed-shell-policy.mjs — do not edit by hand.
# Source: core/policy/destructive-shell.json

cgr_destructive_shell() {
  local cmd="$1"
  if command -v perl >/dev/null 2>&1; then
    printf '%s' "$cmd" | perl -0777 -ne '
${perlChecks.join("\n      ")}
      exit 1;
    '
    return $?
  fi
  printf '%s' "$cmd" | grep -qiE '${grepPattern}'
}
`;

writeFileSync(outPath, body, "utf8");
console.log("Wrote", outPath);
